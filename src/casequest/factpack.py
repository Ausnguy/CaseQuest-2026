"""Generate the Phase 3 fact pack: observed baseline plus modeled candidate strategies.

Usage:  uv run python -m casequest.factpack
"""

from __future__ import annotations

import pandas as pd

from casequest.clean import CleanData, clean_all
from casequest.config import DOCS_DIR
from casequest.metrics import enrich_events, hse_summary, site_context, stage_breakdown, summarize
from casequest.options import Plan, PlanResult, model_plan, sites_to_assets
from casequest.signals import backtest, random_alert_precision, vibration_alerts


def candidate_plans(data: CleanData, events: pd.DataFrame) -> list[Plan]:
    all_assets = tuple(sorted(data.assets["asset_id"]))
    all_sites = sorted(data.sites["site_id"])
    pumps = sites_to_assets(data, all_sites, ["Transfer pump", "Lift pump"])
    o1_by_asset = model_plan(data, events, Plan("probe", {"O1": all_assets})).events.groupby("asset_id")["avoided_hours"].sum()
    top6 = tuple(sorted(o1_by_asset.nlargest(6).index))
    return [
        Plan("A. Spare parts (O4), all 6 sites", {"O4": all_assets}),
        Plan("B. Condition monitoring (O1), all 18 assets", {"O1": all_assets}),
        Plan("C. Work-order workflow (O3), all 6 sites", {"O3": all_assets}),
        Plan("D. Mechanical refurbishment (O5), all 12 pumps", {"O5": pumps}),
        Plan("E. Hybrid: O4 + O3, all sites", {"O4": all_assets, "O3": all_assets}),
        Plan("F. Hybrid: O4 all sites + O1 all assets", {"O4": all_assets, "O1": all_assets}),
        Plan(f"G. Hybrid: O4 all sites + O1 on top-6 assets ({', '.join(top6)})", {"O4": all_assets, "O1": top6}),
        Plan("H. Digital: O1 all assets + O3 all sites", {"O1": all_assets, "O3": all_assets}),
    ]


def _pre_failure_gaps(data: CleanData, events: pd.DataFrame) -> pd.DataFrame:
    mech = events[(events["event_type"] == "Unplanned") & events["cause"].isin(["Bearing wear", "Seal leak"])]
    pairs = mech[["asset_id", "start_utc"]].merge(data.readings[["asset_id", "observed_utc", "quality", "delayed_ingest"]].reset_index(), on="asset_id")
    window = pairs[(pairs["observed_utc"] < pairs["start_utc"]) & (pairs["observed_utc"] >= pairs["start_utc"] - pd.Timedelta(days=7))]
    window = window.drop_duplicates("index").merge(data.assets[["asset_id", "site_id"]], on="asset_id")
    out = window.groupby("site_id").agg(readings=("index", "count"), missing_pct=("quality", lambda s: 100 * (s == "Missing").mean()), delayed_pct=("delayed_ingest", lambda s: 100 * s.mean()))
    return out.reset_index()


def _money(v: float) -> str:
    return f"${v:,.0f}"


def _table(df: pd.DataFrame, floatfmt: str = ",.1f") -> str:
    def fmt(v):
        if isinstance(v, float):
            return format(v, floatfmt)
        return str(v)

    header = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([header, sep, *rows])


def build() -> str:
    data = clean_all()
    events = enrich_events(data)
    unplanned = events[events["event_type"] == "Unplanned"]
    out: list[str] = [
        "# Phase 3 Fact Pack",
        "",
        "_Generated by `uv run python -m casequest.factpack` from the cleaned data. Do not edit by hand._",
        "",
        "Labels: **OBSERVED** = what happened in 2025. **MODELED** = estimate using the Solutions sheet's stage-reduction",
        "fractions under the ReadMe rules; not a promise or a measured result.",
        "",
        "## 1. OBSERVED: 2025 baseline",
        "",
    ]
    by_type = summarize(events, "event_type").reset_index()
    out.append(_table(by_type[["event_type", "events", "downtime_hours", "lost_oil_bbl", "contribution_loss_usd", "known_maintenance_lower_bound_usd", "pending_invoices"]]))
    out += [
        "",
        "Contribution loss uses the ReadMe formula: lost_oil x (1 - recoverable_fraction) x (price - variable_cost) for the asset-month.",
        "Known maintenance cost is a lower bound: pending parts invoices are unknown, not zero.",
        "",
        "### Unplanned downtime by cause",
        "",
    ]
    cause = summarize(unplanned, "cause").reset_index()
    out.append(_table(cause[["cause", "events", "downtime_hours", "hours_share", "contribution_loss_usd", "detect_hours", "dispatch_hours", "parts_wait_hours", "repair_hours", "restart_hours"]], ",.2f"))
    out += ["", "### Unplanned downtime by stage", ""]
    out.append(_table(stage_breakdown(unplanned).reset_index().rename(columns={"index": "stage"}), ",.2f"))
    out += ["", "### Sites: downtime, resources, HSE", ""]
    site = site_context(data, unplanned)
    out.append(_table(site[["site_id", "site_name", "events", "downtime_hours", "contribution_loss_usd", "parts_wait_hours", "spare_fill_pct", "network_uptime_pct", "technicians", "available_project_hours", "open_hse_actions", "open_sev5_actions", "pilot_blocked"]]))
    out += ["", "### Top assets by unplanned downtime", ""]
    assets = summarize(unplanned, ["asset_id", "site_id", "asset_type", "criticality"]).reset_index().head(8)
    out.append(_table(assets[["asset_id", "site_id", "asset_type", "criticality", "events", "downtime_hours", "contribution_loss_usd"]]))
    out += ["", "By asset type and criticality:", ""]
    out.append(_table(summarize(unplanned, "asset_type").reset_index()[["asset_type", "events", "downtime_hours", "contribution_loss_usd"]]))
    out += [""]
    out.append(_table(summarize(unplanned, "criticality").reset_index()[["criticality", "events", "downtime_hours", "contribution_loss_usd"]]))

    hse = hse_summary(data)
    out += [
        "",
        "### HSE (snapshot 2026-10-01)",
        "",
        f"- {hse['observations']} observations: {hse['outcomes']}",
        f"- {hse['open_actions']} open corrective actions, **all {hse['overdue_open_actions']} overdue**",
        f"- {hse['open_sev5_actions']} open potential-severity-5 actions -> **pilot blocked at {', '.join(hse['blocked_sites'])}** until the site HSE supervisor verifies closure",
        f"- Repeated hazard at the same site: {hse['repeated_hazard_site_pairs']} site-hazard pairs; net uncontained spill: {hse['net_spill_bbl']:g} bbl",
        "- ReadMe: no exposure denominator; do not report injury rates or claim incident prevention.",
        "",
        "## 2. OBSERVED: do readings warn before failures? (retrospective backtest)",
        "",
        f"Rule: an alert is a Valid, Running reading above a multiple of the asset's normal vibration. An event counts as detected if an alert was observed in the 7 days before it AND had been received before it started. Results are shown separately for H1 = Jan-Jun and H2 = Jul-Dec to check stability; thresholds were explored on the full year, so H2 is **not** a true hold-out. Random-alert precision baseline: {random_alert_precision(data, events):.2f}.",
        "",
        "| Rule | Period | Bearing wear | Seal leak | Electrical trip | Process upset | Unknown | Alerts | Precision | Median lead (days) |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    rules = [(f"vibration > {k}x normal", vibration_alerts(data, k)) for k in (1.3, 2.0)]
    rules.append(("operator note: abnormal noise", data.readings["inspection_note"].eq("Operator noticed abnormal noise")))
    for name, alert in rules:
        for period in ("H1", "H2"):
            b = backtest(data, events, alert, name, period)
            c = b.detection_by_cause
            out.append(f"| {name} | {period} | {c.get('Bearing wear', 0):.2f} | {c.get('Seal leak', 0):.2f} | {c.get('Electrical trip', 0):.2f} | {c.get('Process upset', 0):.2f} | {c.get('Unknown', 0):.2f} | {b.alerts} | {b.precision:.2f} | {b.median_lead_days} |")
    out += [
        "",
        "**Treat as feasibility, not proof.** Detection and precision near 1.00 are far cleaner than published field results (Navy studies cited by NASA: detection 0.76-0.92, false-alarm rate 0.08), which indicates a generated signal. The backtest does not validate the Solutions reduction fractions. A 2-day median lead on daily snapshots is only 2-3 data points (NASA asks for at least 3 to confirm a trend). Precision counts an unplanned event of any cause within 7 days as a hit.",
        "",
        "Caveats: synthetic scenario data with daily 06:00 snapshots; Dictionary says daily sampling cannot establish production-grade predictive accuracy. Signals exist only for mechanical causes (bearing, seal), matching O1's eligible causes.",
        "",
        "Readings in the 7 days before bearing/seal failures, by site (missing = quality Missing; delayed = received > 1 h after observation):",
        "",
        _table(_pre_failure_gaps(data, events)),
        "",
        "## 3. MODELED: candidate strategies (full steady-state year, base fractions)",
        "",
        "Rules applied: eligible causes and asset types only; overlapping options multiply remaining stage time; protected repair time never reduced; prerequisites (O2 once; O6 + site cleanup per site for O1/O3; edge buffering where uptime < 97% for O1) paid once; open HSE actions at in-scope sites included; implementation hours compared with each site's available project hours, and any shortfall costed at an assumed $85/h (the Events labor rate).",
        "",
        "| Strategy | Avoided h (base) | % of unplanned | Low-High h | Avoided contribution (base) | Upfront | Annual | Months to commission (prereqs first) | Extra planned outage h | Sites over capacity |",
        "|---|---:|---:|---|---:|---:|---:|---:|---:|---|",
    ]
    results: list[PlanResult] = []
    for plan in candidate_plans(data, events):
        base = model_plan(data, events, plan)
        low = model_plan(data, events, Plan(plan.name, plan.scope, "low"))
        high = model_plan(data, events, Plan(plan.name, plan.scope, "high"))
        results.append(base)
        over = base.site_resources[base.site_resources["shortfall_hours"] > 0]
        over_txt = ", ".join(f"{s} (+{h:.0f} h)" for s, h in zip(over["site_id"], over["shortfall_hours"])) or "none"
        out.append(
            f"| {plan.name} | {base.avoided_hours:,.0f} | {base.avoided_share:.1%} | {low.avoided_hours:,.0f}-{high.avoided_hours:,.0f} | "
            f"{_money(base.avoided_contribution_usd)} | {_money(base.upfront_usd)} | {_money(base.annual_usd)} | {base.lead_months} | "
            f"{base.extra_planned_outage_hours:g} | {over_txt} |"
        )
    out += ["", "Every strategy covering S02, S04 or S06 is gated: those sites cannot start a pilot until their open severity-5 HSE actions are verified closed.", ""]
    for r in results:
        out += [f"### {r.plan.name}", "", "Cost lines:", ""]
        out.append(_table(r.cost_lines.assign(units=r.cost_lines["units"].map(lambda v: f"{v:g}"))))
        by_site = r.events.groupby("site_id")["avoided_hours"].sum().round(0)
        out += ["", "Avoided hours by site (base): " + ", ".join(f"{s} {h:,.0f}" for s, h in by_site.items()), ""]
    return "\n".join(out) + "\n"


def main() -> int:
    (DOCS_DIR / "phase-3-fact-pack.md").write_text(build(), encoding="utf-8", newline="\n")
    print(f"Wrote {DOCS_DIR / 'phase-3-fact-pack.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
