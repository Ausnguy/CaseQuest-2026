"""Build the processed dataset and its audit documents.

Usage:  uv run python -m casequest.build
"""

from __future__ import annotations

import hashlib
import sys

from casequest.clean import CleanData, clean_all
from casequest.config import DOCS_DIR, PROCESSED_DIR, RAW_WORKBOOK, RAW_WORKBOOK_SHA256
from casequest.validate import Check, run_checks


def sha256(path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_tables(data: CleanData) -> None:
    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    for name, df in data.tables().items():
        df.to_csv(PROCESSED_DIR / f"{name}.csv", index=False, lineterminator="\n", encoding="utf-8")


def write_doc(name: str, text: str) -> None:
    (DOCS_DIR / name).write_text(text, encoding="utf-8", newline="\n")


def cleaning_log_markdown(data: CleanData, raw_hash: str) -> str:
    lines = [
        "# Cleaning Log",
        "",
        "_Generated by `uv run python -m casequest.build`. Do not edit by hand._",
        "",
        f"Source: `{RAW_WORKBOOK.relative_to(RAW_WORKBOOK.parents[1])}` (read-only)  ",
        f"SHA-256: `{raw_hash}` ({'matches' if raw_hash == RAW_WORKBOOK_SHA256 else 'DOES NOT MATCH'} the Phase 1 fingerprint)",
        "",
        "## Row counts",
        "",
        "| Table | Raw rows | Clean rows |",
        "|---|---:|---:|",
    ]
    clean_counts = {name.capitalize() if name != "hse" else "HSE": len(df) for name, df in data.tables().items()}
    for name, raw_rows in data.raw_row_counts.items():
        lines.append(f"| {name} | {raw_rows:,} | {clean_counts[name]:,} |")
    lines.append(f"| Sites (derived from Assets) | — | {len(data.sites)} |")
    lines += ["", "## Rules applied", "", "| # | Table | Rule | Rows | Why |", "|---:|---|---|---:|---|"]
    for i, entry in enumerate(data.log.entries, 1):
        lines.append(f"| {i} | {entry.table} | {entry.rule} | {entry.rows_affected:,} | {entry.rationale} |")
    lines += ["", "## Affected records", ""]
    for i, entry in enumerate(data.log.entries, 1):
        if entry.examples:
            shown = f" (first {len(entry.examples)} of {entry.rows_affected:,})" if entry.rows_affected > len(entry.examples) else ""
            lines.append(f"**{i}. {entry.table}: {entry.rule}**{shown}  ")
            lines.append(", ".join(f"`{x}`" for x in entry.examples))
            lines.append("")
    return "\n".join(lines) + "\n"


def reconciliation_markdown(checks: list[Check]) -> str:
    passed = sum(c.passed for c in checks)
    lines = [
        "# Reconciliation Checks",
        "",
        "_Generated by `uv run python -m casequest.build`. Do not edit by hand._",
        "",
        f"**{passed} of {len(checks)} checks pass.**",
        "",
        "| Result | Check | Detail |",
        "|---|---|---|",
    ]
    for c in checks:
        lines.append(f"| {'PASS' if c.passed else '**FAIL**'} | {c.name} | {c.detail} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    raw_hash = sha256(RAW_WORKBOOK)
    if raw_hash != RAW_WORKBOOK_SHA256:
        print(f"Raw workbook hash {raw_hash} does not match the Phase 1 fingerprint; refusing to build.", file=sys.stderr)
        return 1
    data = clean_all()
    checks = run_checks(data)
    write_doc("reconciliation.md", reconciliation_markdown(checks))
    failed = [c for c in checks if not c.passed]
    print(f"{len(checks) - len(failed)}/{len(checks)} reconciliation checks pass")
    if failed:
        for c in failed:
            print(f"FAIL: {c.name}: {c.detail}", file=sys.stderr)
        print("Processed tables NOT written because checks failed.", file=sys.stderr)
        return 1
    write_tables(data)
    write_doc("cleaning-log.md", cleaning_log_markdown(data, raw_hash))
    if sha256(RAW_WORKBOOK) != raw_hash:
        print("Raw workbook changed during build", file=sys.stderr)
        return 1
    print(f"Wrote {len(data.tables())} tables to {PROCESSED_DIR}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
